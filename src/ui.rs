/// The cold-boot splash.
///
/// Worth the four seconds it costs. A device that takes nearly a minute to say
/// anything useful — the sensor has to settle, and the first status screen is
/// gated behind a batch window — otherwise gives no sign it started at all, and
/// "did it boot?" is the first question anyone asks of a box with one button.
pub fn logo(frame: &mut Display7in5) {
    let _ = frame.clear(PAPER);

    // Centred on both axes. The artwork is 480x480 on an 800x480 panel, so it
    // is full-height and the centring only does anything horizontally -- but
    // computing it means a re-exported logo of another size still lands right.
    let at = Point::new(
        (WIDTH as i32 - LOGO.width as i32) / 2,
        (HEIGHT as i32 - LOGO.height as i32) / 2,
    );
    blit(frame, &LOGO, at);

    let mut version = Text32::new();
    let _ = version.push_str("fw ");
    let _ = version.push_str(env!("CARGO_PKG_VERSION"));
    let _ = Text::with_alignment(
        &version,
        Point::new(WIDTH as i32 - 16, HEIGHT as i32 - 22),
        MonoTextStyle::new(&FONT_9X15, INK),
        Alignment::Right,
    )
    .draw(frame);

    // Bottom left, balancing the version on the right. The artwork is 480 px
    // wide and centred on an 800 px panel, so it occupies x=160..640 — both
    // bottom corners are clear of it whatever the logo contains.
    let _ = Text::with_baseline(
        AUTHOR,
        Point::new(16, HEIGHT as i32 - 26),
        MonoTextStyle::new(&FONT_9X15, INK),
        Baseline::Top,
    )
    .draw(frame);
}

/// The number meant to be read from across the room.
const HEADLINE: FontRenderer = FontRenderer::new::<fonts::u8g2_font_fub42_tr>();
/// Section headings and gauge labels.
const LABEL: FontRenderer = FontRenderer::new::<fonts::u8g2_font_fub14_tr>();

type Text16 = heapless::String<16>;
type Text32 = heapless::String<32>;
type Text64 = heapless::String<64>;

/// Top of the status line's text.
///
/// Not zero: the panel's first rows are the ones most likely to be lost to a
/// bezel or a marginal edge, and a status line that has to be read at an angle
/// should not start at the very first pixel.
const STATUS_TOP: i32 = 6;

/// Everything the status screen shows.
pub struct Status {
    pub location: Location,
    /// Measured antenna resonance, kHz — from the LCO self-test.
    pub antenna_khz: u32,
    pub irq_confirmed: bool,
    /// §4.2's defence level and its ceiling.
    pub defence_level: u8,
    pub defence_max: u8,
    pub strikes_total: u32,
    /// The most recent strike, if there has been one.
    pub last_strike: Option<(Distance, u32)>,
    /// Disturbers counted since boot — the honest measure of how hostile the
    /// location is, and the number that decides whether a quiet screen means
    /// "no storms" or "this spot is unusable".
    pub disturbers_total: u32,
    /// Device health, drawn as the status line.
    pub health: Health,
    /// `None` when the gauge is absent or did not answer.
    pub battery: Option<crate::battery::Reading>,
    /// Minutes since boot, for the uptime readout.
    pub uptime_minutes: u32,
    /// Everything seen in the last hour (§4.3).
    pub last_hour: crate::history::Bucket,
    /// The learned cell range, low/high mV (§2.1).
    pub battery_range: (u16, u16),
}

/// Draw the status screen.
pub fn status(frame: &mut Display7in5, s: &Status) {
    let _ = frame.clear(PAPER);
    let black = PrimitiveStyle::with_stroke(INK, 1);

    // --- status line ------------------------------------------------------
    //
    // The device talking about itself: clock, die temperature, memory, battery.
    // One line, at the top, small. In a box that runs unattended for weeks this
    // is the only way to ask whether the machine under the readings is healthy —
    // and none of it is about the weather, which is why it is kept out of the
    // way of everything that is.
    status_line(frame, s);

    let _ = Line::new(Point::new(16, 30), Point::new(WIDTH as i32 - 16, 30))
        .into_styled(black)
        .draw(frame);

    // --- mode and noise defence -------------------------------------------
    //
    // This row used to read "LIGHTNING TERMINAL", which is the one fact anyone
    // looking at the device already knows. It now carries the two settings that
    // change how the sensor behaves and that nothing else on screen reveals:
    // which AFE gain is selected, and how hard the receiver is currently
    // fighting noise.
    let mut mode = Text32::new();
    let _ = mode.push_str("Mode: ");
    let _ = mode.push_str(s.location.label());
    let _ = LABEL.render(
        mode.as_str(),
        Point::new(16, 62),
        VerticalPosition::Baseline,
        FontColor::Transparent(INK),
        frame,
    );
    // What changes it, said on the glass. There is exactly one button and no
    // other label anywhere on the device, so a sealed box otherwise gives no
    // clue that pressing it does anything at all.
    let _ = Text::with_baseline(
        "BOOT switches",
        Point::new(16, 70),
        MonoTextStyle::new(&FONT_6X10, INK),
        Baseline::Top,
    )
    .draw(frame);

    // The gauge sits on this row rather than in the middle of the screen: it is
    // a setting, not a measurement, and it belongs beside the other one.
    gauge(
        frame,
        Point::new(230, 62),
        s.defence_level as u32,
        s.defence_max as u32,
    );

    let _ = Line::new(Point::new(16, 84), Point::new(WIDTH as i32 - 16, 84))
        .into_styled(black)
        .draw(frame);

    // --- the headline: total strikes --------------------------------------
    //
    // The one number the device exists to report. Everything else on this
    // screen is context for it.
    let mut count = Text16::new();
    let _ = write_u32(&mut count, s.strikes_total);
    let _ = HEADLINE.render(
        count.as_str(),
        Point::new(16, 158),
        VerticalPosition::Baseline,
        FontColor::Transparent(INK),
        frame,
    );
    let _ = LABEL.render(
        if s.strikes_total == 1 { "strike" } else { "strikes" },
        Point::new(16, 190),
        VerticalPosition::Baseline,
        FontColor::Transparent(INK),
        frame,
    );

    // --- the last hour ----------------------------------------------------
    //
    // §4.3's three figures. Count says how *busy*, mean score says how *severe*,
    // and distance says how *close* -- and none of the three substitutes for
    // another. One violent overhead strike and a hundred distant ones produce
    // the same count and wildly different scores; the reverse is true of the
    // mean.
    stats(frame, s);

    // --- last strike ------------------------------------------------------
    let mut last = Text32::new();
    match s.last_strike {
        Some((distance, intensity_milli)) => {
            let _ = last.push_str(match distance {
                Distance::Overhead => "overhead",
                Distance::OutOfRange => "out of range",
                Distance::Km(_) => "",
            });
            if let Distance::Km(km) = distance {
                let _ = write_u32(&mut last, km as u32);
                let _ = last.push_str(" km");
            }
            let _ = last.push_str("  ·  intensity ");
            let _ = write_u32(&mut last, intensity_milli / 1000);
        }
        None => {
            let _ = last.push_str("no strikes yet");
        }
    }
    let _ = Text::with_baseline(
        &last,
        Point::new(320, 138),
        MonoTextStyle::new(&FONT_10X20, INK),
        Baseline::Top,
    )
    .draw(frame);

    // --- the bring-up facts, small, at the foot ---------------------------
    //
    // Small because they matter once — but they matter a lot then, and a sealed
    // device with no console has nowhere else to say them.
    let mut antenna = Text32::new();
    let _ = antenna.push_str("antenna ");
    let _ = write_u32(&mut antenna, s.antenna_khz);
    let _ = antenna.push_str(" kHz · IRQ ");
    let _ = antenna.push_str(if s.irq_confirmed { "OK" } else { "NOT CONFIRMED" });
    let _ = antenna.push_str(" · disturbers ");
    let _ = write_u32(&mut antenna, s.disturbers_total);
    // The learned cell range, small and at the foot. It is a slow-moving
    // diagnostic rather than a reading — but it is the number that says whether
    // the runtime prediction above it has anything behind it, and a pack whose
    // observed maximum has fallen is a cell that is ageing.
    let _ = antenna.push_str(" · cell ");
    let _ = write_u32(&mut antenna, s.battery_range.0 as u32);
    let _ = antenna.push('-');
    let _ = write_u32(&mut antenna, s.battery_range.1 as u32);
    let _ = antenna.push_str(" mV");

    let _ = Line::new(
        Point::new(16, HEIGHT as i32 - 40),
        Point::new(WIDTH as i32 - 16, HEIGHT as i32 - 40),
    )
    .into_styled(black)
    .draw(frame);
    let _ = Text::with_baseline(
        &antenna,
        Point::new(16, HEIGHT as i32 - 32),
        MonoTextStyle::new(&FONT_6X10, INK),
        Baseline::Top,
    )
    .draw(frame);
}

/// A labelled horizontal bar.
///
/// Deliberately a bar rather than a number: the question these answer is "how
/// close to the limit", which a filled proportion says at a glance and a
/// figure makes you compute.
fn gauge(frame: &mut Display7in5, at: Point, value: u32, max: u32) {
    const BAR_WIDTH: u32 = 260;
    const BAR_HEIGHT: u32 = 22;

    let _ = LABEL.render(
        "Noise level",
        Point::new(at.x, at.y),
        VerticalPosition::Baseline,
        FontColor::Transparent(INK),
        frame,
    );

    // Cleared to the right of the label, which is wider than "noise" was.
    const LABEL_WIDTH: i32 = 130;
    let bar = Rectangle::new(
        Point::new(at.x + LABEL_WIDTH, at.y - 16),
        Size::new(BAR_WIDTH, BAR_HEIGHT),
    );
    let _ = bar
        .into_styled(PrimitiveStyle::with_stroke(INK, 2))
        .draw(frame);

    if max > 0 && value > 0 {
        // Inset by the stroke so the fill does not sit on the border.
        let filled = (BAR_WIDTH - 4) * value.min(max) / max;
        let _ = Rectangle::new(
            Point::new(at.x + LABEL_WIDTH + 2, at.y - 14),
            Size::new(filled, BAR_HEIGHT - 4),
        )
        .into_styled(PrimitiveStyle::with_fill(INK))
        .draw(frame);
    }

    // The number alone. The rung name -- "noise floor", "watchdog", "spike
    // rejection" -- is which register the ladder happens to be working on, and
    // that is a fact about the implementation rather than about the weather. It
    // stays on the console, where it is a debugging aid.
    let mut caption = Text32::new();
    let _ = write_u32(&mut caption, value);
    let _ = caption.push('/');
    let _ = write_u32(&mut caption, max);
    let _ = Text::with_baseline(
        &caption,
        Point::new(at.x + LABEL_WIDTH + BAR_WIDTH as i32 + 12, at.y - 14),
        MonoTextStyle::new(&FONT_9X15, INK),
        Baseline::Top,
    )
    .draw(frame);
}

/// Append a decimal `u32` without `format!`.
///
/// The render path runs on a device that is meant to stay up for weeks;
/// `format!` allocates, and the allocation is avoidable here for the sake of
/// four lines.
fn write_u32<const N: usize>(out: &mut heapless::String<N>, mut value: u32) -> Result<(), ()> {
    if value == 0 {
        return out.push('0').map_err(|_| ());
    }
    let mut digits = [0u8; 10];
    let mut used = 0;
    while value > 0 {
        digits[used] = b'0' + (value % 10) as u8;
        value /= 10;
        used += 1;
    }
    for i in (0..used).rev() {
        out.push(digits[i] as char).map_err(|_| ())?;
    }
    Ok(())
}


/// The device's own vital signs, as one line.
fn status_line(frame: &mut Display7in5, s: &Status) {
    let style = MonoTextStyle::new(&FONT_9X15, INK);
    let mut left = Text64::new();

    // Uptime first: it is the number that says whether anything below it has
    // had time to mean anything.
    let _ = left.push_str("up ");
    let hours = s.uptime_minutes / 60;
    if hours > 0 {
        let _ = write_u32(&mut left, hours);
        let _ = left.push('h');
    }
    let _ = write_u32(&mut left, s.uptime_minutes % 60);
    let _ = left.push_str("m");

    let _ = left.push_str("   ");
    let _ = write_u32(&mut left, s.health.cpu_mhz);
    let _ = left.push_str(" MHz");

    if let Some(tenths) = s.health.die_temp_tenths {
        let _ = left.push_str("   die ");
        if tenths < 0 {
            let _ = left.push('-');
        }
        let magnitude = tenths.unsigned_abs();
        let _ = write_u32(&mut left, magnitude / 10);
        let _ = left.push('.');
        let _ = write_u32(&mut left, magnitude % 10);
        let _ = left.push_str(" C");
    }

    let _ = left.push_str("   heap ");
    let _ = write_u32(&mut left, s.health.free_heap_kb);
    let _ = left.push_str(" KB");

    let _ = Text::with_baseline(&left, Point::new(16, STATUS_TOP), style, Baseline::Top).draw(frame);

    // Battery on the right, because it is the one field a passer-by looks for.
    let mut right = Text64::new();
    match s.battery {
        Some(reading) => {
            let _ = right.push_str("Battery ");
            let _ = write_u32(&mut right, reading.percent as u32);
            let _ = right.push_str("%  ");
            let _ = write_u32(&mut right, reading.millivolts as u32 / 1000);
            let _ = right.push('.');
            let hundredths = (reading.millivolts % 1000) / 10;
            if hundredths < 10 {
                let _ = right.push('0');
            }
            let _ = write_u32(&mut right, hundredths as u32);
            let _ = right.push_str(" V");

            if reading.is_charging() {
                let _ = right.push_str("  charging");
            } else {
                // **Two predictions, and the learned one wins where it exists.**
                //
                // The gauge divides its own percentage by its own rate — self-
                // consistent, and wrong in the same direction as the gauge
                // whenever the gauge is wrong about this cell. The learned
                // figure asks how much of the range *this unit has actually
                // observed* is left, and how fast it is being crossed.
                //
                // They part company near empty, where a LiPo falls off a cliff
                // and a percentage flatters the time remaining. The learned one
                // is preferred once the observed span is wide enough to divide
                // by; until then there is nothing to prefer and the gauge's
                // model is the better guess.
                let hours = crate::battery::hours_from_range(s.battery_range, &reading)
                    .or_else(|| reading.hours_remaining());
                if let Some(hours) = hours {
                    let _ = right.push_str("  ");
                    if hours >= 48 {
                        let _ = write_u32(&mut right, hours / 24);
                        let _ = right.push_str("d left");
                    } else {
                        let _ = write_u32(&mut right, hours);
                        let _ = right.push_str("h left");
                    }
                }
                // No figure at all when neither can answer. §2.1's CRATE is a
                // real measurement, and a device that has just woken has not
                // discharged measurably yet — a number there would be a
                // division by nearly zero wearing a hat.
            }
        }
        None => {
            let _ = right.push_str("Battery -- no gauge");
        }
    }

    // **Right-aligned AND top-baselined.** `Text::with_alignment` alone leaves
    // the vertical baseline at its default -- alphabetic -- which draws the text
    // *above* the given y. At the top of the panel that clips the first few
    // pixel rows off the glass, while the left-hand half of the same line sits
    // correctly because it was built with `with_baseline`. Two calls, two
    // different defaults, one line that looked half-broken.
    let right_style = TextStyleBuilder::new()
        .alignment(Alignment::Right)
        .baseline(Baseline::Top)
        .build();
    let _ = Text::with_text_style(
        &right,
        Point::new(WIDTH as i32 - 16, STATUS_TOP),
        style,
        right_style,
    )
    .draw(frame);
}


/// The last hour's three figures, in a row under the headline.
fn stats(frame: &mut Display7in5, s: &Status) {
    const TOP: i32 = 232;
    const COLUMN: i32 = 190;

    let hour = &s.last_hour;

    let mut count = Text16::new();
    let _ = write_u32(&mut count, hour.strikes as u32);
    stat(frame, Point::new(16, TOP), "strikes / hour", &count);

    let mut score = Text16::new();
    match hour.mean_score_milli() {
        Some(milli) => {
            let _ = write_u32(&mut score, milli / 1000);
            let _ = score.push('.');
            let hundredths = (milli % 1000) / 10;
            if hundredths < 10 {
                let _ = score.push('0');
            }
            let _ = write_u32(&mut score, hundredths);
        }
        // A dash, not a zero. Zero is a score, and an hour with no strikes did
        // not score zero -- it has no score at all, and the two mean opposite
        // things about the weather.
        None => {
            let _ = score.push('-');
        }
    }
    stat(frame, Point::new(16 + COLUMN, TOP), "mean score", &score);

    let mut distance = Text16::new();
    match hour.mean_distance_km() {
        Some(km) => {
            let _ = write_u32(&mut distance, km);
            let _ = distance.push_str(" km");
        }
        None => {
            let _ = distance.push('-');
        }
    }
    stat(frame, Point::new(16 + COLUMN * 2, TOP), "mean distance", &distance);

    let mut closest = Text16::new();
    if hour.distance_km_min == u8::MAX {
        let _ = closest.push('-');
    } else {
        let _ = write_u32(&mut closest, hour.distance_km_min as u32);
        let _ = closest.push_str(" km");
    }
    stat(frame, Point::new(16 + COLUMN * 3, TOP), "closest", &closest);
}

/// One labelled figure: value large, label small beneath it.
fn stat(frame: &mut Display7in5, at: Point, label: &str, value: &str) {
    let _ = LABEL.render(
        value,
        Point::new(at.x, at.y),
        VerticalPosition::Baseline,
        FontColor::Transparent(INK),
        frame,
    );
    let _ = Text::with_baseline(
        label,
        Point::new(at.x, at.y + 8),
        MonoTextStyle::new(&FONT_9X15, INK),
        Baseline::Top,
    )
    .draw(frame);
}
